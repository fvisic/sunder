package crypto

// GF(256) Shamir secret sharing for F9 (recovery-key custody). A secret is
// split into n shares of which any k reconstruct it; k-1 shares reveal
// nothing. Each secret byte is shared independently in GF(2^8) using the
// AES/Rijndael reduction polynomial 0x11B, so a share is just a 1-byte X
// coordinate followed by one Y byte per secret byte.
//
// Stdlib-only by policy: the field arithmetic is hand-rolled over log/antilog
// tables and the only outside input is crypto/rand for the polynomial
// coefficients. No new module dependency is introduced.
//
// Security note: CombineShares cannot know the original threshold k, so it
// interpolates through whatever shares it is handed. Too few (or wrong)
// shares yield wrong bytes with NO error - that indistinguishability is the
// whole point of the scheme. Callers that need a pass/fail signal use the
// SplitWithChecksum / CombineWithChecksum pair below.

import (
	"crypto/sha256"
	"crypto/subtle"
	"errors"
	"fmt"
)

// ErrInsufficientShares is returned by CombineWithChecksum when the embedded
// checksum does not match the reconstructed secret - i.e. too few shares, or
// shares that do not belong together, were supplied.
var ErrInsufficientShares = errors.New("crypto: insufficient or mismatched shares")

// checksumLen is the number of leading SHA-256 bytes SplitWithChecksum binds
// to the secret. Four bytes give a ~1-in-4-billion chance that a wrong
// combine passes by accident, which is ample for custody recovery.
const checksumLen = 4

// gfExp and gfLog are the antilog/log tables over GF(2^8) generated by 0x03,
// a generator of the multiplicative group. gfExp[i] = 0x03^i and gfLog[a] is
// its inverse; gfLog[0] is unused. gfExp is doubled to length 512 so gfMul
// can index it with a sum of two logs (each up to 254, so up to 508) without
// a modulo - the upper half repeats the lower.
var (
	gfExp [512]byte
	gfLog [256]byte
)

func init() {
	// Walk the cyclic group generated by 0x03. After 255 steps we must land
	// back on 1; if we did not, 0x03 would not be a generator and every
	// operation built on these tables would be wrong - so assert it.
	x := byte(1)
	for i := 0; i < 255; i++ {
		gfExp[i] = x
		gfLog[x] = byte(i)
		x = xtimesPlus(x) // x *= 0x03
	}
	if x != 1 {
		panic("crypto: 0x03 is not a generator of GF(2^8) - table build broken")
	}
	// Period is 255; repeat it so any log sum in [0, 508] indexes directly.
	for i := 255; i < len(gfExp); i++ {
		gfExp[i] = gfExp[i-255]
	}
}

// xtimesPlus multiplies a by 0x03 in GF(2^8): a*0x03 = a*0x02 XOR a. The
// a*0x02 (xtime) step shifts left and reduces by 0x11B when bit 7 was set.
func xtimesPlus(a byte) byte {
	x2 := a << 1
	if a&0x80 != 0 {
		x2 ^= 0x1B // 0x11B minus the x^8 term that the shift dropped
	}
	return x2 ^ a
}

// gfMul multiplies in GF(2^8) via the log tables: a*b = antilog(log a + log b),
// with 0 absorbing as usual.
func gfMul(a, b byte) byte {
	if a == 0 || b == 0 {
		return 0
	}
	return gfExp[int(gfLog[a])+int(gfLog[b])]
}

// gfInv returns the multiplicative inverse of a (a != 0). inv(a) = antilog(255
// - log a), since a * antilog(255 - log a) = antilog(255) = antilog(0) = 1.
func gfInv(a byte) byte {
	if a == 0 {
		panic("crypto: GF(2^8) inverse of zero")
	}
	return gfExp[255-int(gfLog[a])]
}

// SplitSecret splits secret into n shares, any k of which reconstruct it.
// Each byte of the secret is shared independently over GF(2^8) with the
// AES/Rijndael reduction polynomial 0x11B. Returns n shares; each share is
// (1 + len(secret)) bytes: a 1-byte non-zero X coordinate followed by the
// Y byte per secret byte. Requires 2 <= k <= n <= 255 and len(secret) >= 1.
func SplitSecret(secret []byte, n, k int) ([][]byte, error) {
	return splitWithCoeffs(secret, n, k, randRead)
}

// splitWithCoeffs is the SplitSecret core with the randomness source injected.
// Tests substitute a deterministic reader to pin known-answer vectors; the
// exported path always uses the kernel CSPRNG.
func splitWithCoeffs(secret []byte, n, k int, read func([]byte) (int, error)) ([][]byte, error) {
	if k < 2 {
		return nil, fmt.Errorf("crypto: threshold k=%d must be at least 2", k)
	}
	if n < k {
		return nil, fmt.Errorf("crypto: shares n=%d must be at least threshold k=%d", n, k)
	}
	if n > 255 {
		return nil, fmt.Errorf("crypto: shares n=%d exceeds GF(2^8) maximum of 255", n)
	}
	if len(secret) == 0 {
		return nil, fmt.Errorf("crypto: secret must be non-empty")
	}

	// One degree-(k-1) polynomial per secret byte. a_0 is the secret byte;
	// a_1..a_{k-1} are fresh random field elements. The share at X is the
	// stack of every polynomial evaluated at X.
	shares := make([][]byte, n)
	for i := 0; i < n; i++ {
		// X coordinates are 1..n. Zero is reserved: it is exactly where the
		// secret lives (f(0) = a_0), so handing it out would be handing out
		// the secret.
		x := byte(i + 1)
		share := make([]byte, 1+len(secret))
		share[0] = x
		shares[i] = share
	}

	coeffs := make([]byte, k-1)
	for b := 0; b < len(secret); b++ {
		if _, err := read(coeffs); err != nil {
			return nil, err
		}
		for i := 0; i < n; i++ {
			shares[i][1+b] = evalPoly(secret[b], coeffs, shares[i][0])
		}
	}
	return shares, nil
}

// evalPoly evaluates a_0 + a_1*x + ... + a_{k-1}*x^{k-1} in GF(2^8) via Horner,
// with a0 the constant term and higher[j] = a_{j+1}.
func evalPoly(a0 byte, higher []byte, x byte) byte {
	y := byte(0)
	for j := len(higher) - 1; j >= 0; j-- {
		y = gfMul(y, x) ^ higher[j]
	}
	return gfMul(y, x) ^ a0
}

// CombineShares reconstructs the secret from k or more shares via Lagrange
// interpolation at x=0 over GF(2^8). Shares must have distinct non-zero X
// coordinates and equal length. Fewer than the original k shares yields
// wrong bytes with no error (that is the security property), so the caller
// must verify the result out of band (see below).
func CombineShares(shares [][]byte) ([]byte, error) {
	if len(shares) < 1 {
		return nil, fmt.Errorf("crypto: need at least one share to combine")
	}
	width := len(shares[0])
	if width < 2 {
		return nil, fmt.Errorf("crypto: share too short - want 1 X byte plus at least 1 Y byte")
	}

	xs := make([]byte, len(shares))
	seen := make(map[byte]bool, len(shares))
	for i, s := range shares {
		if len(s) != width {
			return nil, fmt.Errorf("crypto: share %d length %d differs from %d", i, len(s), width)
		}
		x := s[0]
		if x == 0 {
			return nil, fmt.Errorf("crypto: share %d has X coordinate 0, which is reserved for the secret", i)
		}
		if seen[x] {
			return nil, fmt.Errorf("crypto: duplicate X coordinate %d among shares", x)
		}
		seen[x] = true
		xs[i] = x
	}

	// Precompute the Lagrange basis weights L_i(0) once - they depend only on
	// the X coordinates, not on which secret byte we are interpolating.
	//   L_i(0) = prod_{m!=i} x_m / (x_m - x_i)   (subtraction is XOR here)
	weights := make([]byte, len(shares))
	for i := range shares {
		num := byte(1)
		den := byte(1)
		for m := range shares {
			if m == i {
				continue
			}
			num = gfMul(num, xs[m])
			den = gfMul(den, xs[i]^xs[m])
		}
		weights[i] = gfMul(num, gfInv(den))
	}

	secret := make([]byte, width-1)
	for b := 0; b < width-1; b++ {
		acc := byte(0)
		for i, s := range shares {
			acc ^= gfMul(s[1+b], weights[i])
		}
		secret[b] = acc
	}
	return secret, nil
}

// SplitWithChecksum splits secret and prepends a 4-byte SHA-256 prefix of
// the secret to the shared payload, so CombineWithChecksum can report
// whether enough correct shares were supplied instead of returning garbage.
func SplitWithChecksum(secret []byte, n, k int) ([][]byte, error) {
	if len(secret) == 0 {
		// Guard here too so the checksum prefix never stands in for an empty
		// secret and masks the validation SplitSecret would otherwise do.
		return nil, fmt.Errorf("crypto: secret must be non-empty")
	}
	sum := sha256.Sum256(secret)
	// Share the checksum together with the secret so it is protected by the
	// same threshold: a sub-threshold combine corrupts the checksum exactly
	// as it corrupts the secret, which is what lets the check catch it.
	payload := make([]byte, 0, checksumLen+len(secret))
	payload = append(payload, sum[:checksumLen]...)
	payload = append(payload, secret...)
	return SplitSecret(payload, n, k)
}

// CombineWithChecksum reconstructs and verifies the checksum; returns
// ErrInsufficientShares if the checksum does not match (too few or wrong shares).
func CombineWithChecksum(shares [][]byte) ([]byte, error) {
	payload, err := CombineShares(shares)
	if err != nil {
		return nil, err
	}
	if len(payload) < checksumLen+1 {
		return nil, fmt.Errorf("crypto: checksummed payload too short")
	}
	secret := payload[checksumLen:]
	want := sha256.Sum256(secret)
	// Constant-time: the checksum is a MAC-like verifier, so a byte-at-a-time
	// early exit would time-leak how many leading bytes matched.
	if subtle.ConstantTimeCompare(payload[:checksumLen], want[:checksumLen]) != 1 {
		return nil, ErrInsufficientShares
	}
	return secret, nil
}
